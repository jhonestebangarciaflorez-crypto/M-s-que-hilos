// 2. FUNCIÓN PRINCIPAL PARA CAMBIAR Y GUARDAR EL IDIOMA
window.cambiarIdioma = function(idioma) {
  // Guardar la preferencia en el navegador del usuario
  localStorage.setItem('idioma_preferido_crochet', idioma);
  
  // Cambiar el atributo lang de la etiqueta <html> (Buena práctica SEO/Accesibilidad)
  document.documentElement.lang = idioma;

  // Busca todos los elementos que tienen el atributo data-i18n
  const elementos = document.querySelectorAll('[data-i18n]');
  
  elementos.forEach(elemento => {
    const clave = elemento.getAttribute('data-i18n');
    
    // Si la clave existe en nuestro diccionario de traducción
    if (traducciones[idioma] && traducciones[idioma][clave]) {
      // Si el elemento es un input o textarea, se debe cambiar el placeholder
      if (elemento.tagName.toLowerCase() === 'input' || elemento.tagName.toLowerCase() === 'textarea') {
        elemento.placeholder = traducciones[idioma][clave];
      } 
      // Si es texto normal o tiene etiquetas dentro
      else {
        elemento.innerHTML = traducciones[idioma][clave];
      }
    }
  });

  // Disparar un evento personalizado (Opcional, pero útil si otros scripts necesitan saber que el idioma cambió)
  window.dispatchEvent(new CustomEvent('idiomaCambiado', { detail: { idioma: idioma } }));
};

// 3. AUTO-EJECUCIÓN AL CARGAR LA PÁGINA
document.addEventListener('DOMContentLoaded', () => {
  // Buscar si ya existe una preferencia guardada, si no, usar 'es' por defecto
  const idiomaGuardado = localStorage.getItem('idioma_preferido_crochet') || 'es';
  
  // Si el idioma guardado es inglés, aplicamos la traducción automáticamente.
  if (idiomaGuardado !== 'es') {
    window.cambiarIdioma(idiomaGuardado);
  } else {
    document.documentElement.lang = 'es';
  }
});

// Función para obtener una traducción directa por su clave según el idioma actual
window.traducirTexto = function(clave) {
  const idiomaActual = localStorage.getItem('idioma_preferido_crochet') || 'es';
  if (traducciones[idiomaActual] && traducciones[idiomaActual][clave]) {
    return traducciones[idiomaActual][clave];
  }
  // Si no encuentra la traducción, devuelve la clave por defecto
  return clave;
};



